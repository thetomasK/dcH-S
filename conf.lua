function love.conf(t)
    t.window.title = "My Game"
    t.window.fullscreen = false             -- Start in windowed mode
    t.window.borderless = false             -- Keep window borders
    t.window.resizable = true               -- Allow resizing the window
    t.window.width = 1280                   -- Set initial window width
    t.window.height = 720                   -- Set initial window height
    t.console = true                        -- Show debug console (optional)
end
