function love.conf(t)
    t.window.title = "My Game"  -- The window title
    t.window.width = 800        -- Width of the window
    t.window.height = 600       -- Height of the window
    t.window.resizable = true   -- Allows the window to be resized
    t.window.vsync = true       -- Enable vertical sync
    t.console = true            -- Show console (useful for debugging)
end

    